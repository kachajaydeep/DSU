/* Difference BetWeen OOPs and POP

 oops:

-> Oop Stands For Object Oriented Programing
-> Oop Deals With Objects and their Properties.
-> Bottom-Up Approach.
-> Data can be hidden using Encapsulation.
-> Method Overriding and Overloading are used in oops

====================================================================================

POP:
-> POP Stands for Procedure Oriented Programing.
-> POP Deals with Function and Procedures.
-> Top-Down approach.
-> Ther is no data-hiding mechanism.
-> the POP does not support Polymorphism meaning function
   or procedures can't take Multiple Forms.

*/

/* In Short Procedural Programing is about writing procedure or methods that Performs operation on the data,
 while object-oriented programming are used to create an objects that contain both data and methods. */ 




